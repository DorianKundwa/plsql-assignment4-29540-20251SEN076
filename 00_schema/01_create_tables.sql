BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'PAYROLL_AUDIT_LOG', 'ATTENDANCE', 'ALLOWANCES', 'EMPLOYEES', 'ROLES', 'DEPARTMENTS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

CREATE TABLE departments (
    department_id NUMBER PRIMARY KEY,
    department_name VARCHAR2(100) NOT NULL UNIQUE,
    location VARCHAR2(100) NOT NULL
);

CREATE TABLE roles (
    role_id NUMBER PRIMARY KEY,
    role_name VARCHAR2(100) NOT NULL UNIQUE,
    min_salary NUMBER(10, 2) CHECK (min_salary > 0),
    max_salary NUMBER(10, 2),
    CONSTRAINT chk_role_sal_range CHECK (max_salary >= min_salary)
);

CREATE TABLE employees (
    employee_id NUMBER PRIMARY KEY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    phone_number VARCHAR2(20),
    hire_date DATE DEFAULT SYSDATE NOT NULL,
    department_id NUMBER NOT NULL,
    role_id NUMBER NOT NULL,
    salary NUMBER(10, 2) NOT NULL CHECK (salary > 0),
    bonus NUMBER(10, 2) DEFAULT 0 CHECK (bonus >= 0),
    CONSTRAINT fk_emp_dept FOREIGN KEY (department_id) REFERENCES departments(department_id),
    CONSTRAINT fk_emp_role FOREIGN KEY (role_id) REFERENCES roles(role_id)
);

CREATE TABLE allowances (
    allowance_id NUMBER PRIMARY KEY,
    role_id NUMBER NOT NULL,
    allowance_name VARCHAR2(100) NOT NULL,
    allowance_amount NUMBER(10, 2) NOT NULL CHECK (allowance_amount > 0),
    is_applicable CHAR(1) DEFAULT 'Y' CHECK (is_applicable IN ('Y', 'N')),
    CONSTRAINT fk_allow_role FOREIGN KEY (role_id) REFERENCES roles(role_id) ON DELETE CASCADE
);

CREATE TABLE attendance (
    attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id NUMBER NOT NULL,
    attendance_date DATE NOT NULL,
    status VARCHAR2(20) NOT NULL CHECK (status IN ('Present', 'Absent', 'Leave')),
    CONSTRAINT fk_att_emp FOREIGN KEY (employee_id) REFERENCES employees(employee_id) ON DELETE CASCADE,
    CONSTRAINT uq_emp_att_date UNIQUE (employee_id, attendance_date)
);

CREATE TABLE payroll_audit_log (
    log_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id NUMBER,
    old_salary NUMBER(10, 2),
    new_salary NUMBER(10, 2),
    operation_type VARCHAR2(50),
    log_date TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE INDEX idx_emp_dept ON employees(department_id);
CREATE INDEX idx_emp_role ON employees(role_id);
